import os

from dotenv import load_dotenv
from typing import TypedDict

from langgraph.graph import (
    StateGraph,
    START,
    END
)

from langchain_openai import ChatOpenAI


load_dotenv()


# ==================================================
# 1. 定义 State
# ==================================================

class AgentState(TypedDict):

    # 用户原始问题
    user_question: str

    # 商品基础数据
    product_id: str
    ctr: float
    cvr: float

    # 中间分析结果
    diagnosis: str

    # 最终报告
    final_report: str


# ==================================================
# 2. 初始化 LLM
# ==================================================

llm = ChatOpenAI(
    model="deepseek-v4-flash",
    api_key=os.getenv("DEEPSEEK_API_KEY"),
    base_url="https://api.deepseek.com",
    extra_body={
        "thinking": {
            "type": "disabled"
        }
    }
)


# ==================================================
# 3. Node 1：诊断
# ==================================================

def diagnose_node(state: AgentState):

    print("\n===== Diagnose Node =====")

    prompt = f"""
你是一名电商数据分析专家。

用户问题：
{state["user_question"]}

商品：
{state["product_id"]}

CTR：
{state["ctr"]}

CVR：
{state["cvr"]}

请根据现有信息进行初步诊断。

注意：
只能根据已有数据判断，
不能编造不存在的数据。
"""

    response = llm.invoke(prompt)

    return {
        "diagnosis": response.content
    }


# ==================================================
# 4. Node 2：生成报告
# ==================================================

def report_node(state: AgentState):

    print("\n===== Report Node =====")

    prompt = f"""
你是一名电商运营分析专家。

用户问题：
{state["user_question"]}

初步诊断：
{state["diagnosis"]}

请整理成简洁的最终业务分析报告。

必须区分：
1. 已知事实
2. 可以合理推断的内容
3. 目前无法判断、需要补充的数据
"""

    response = llm.invoke(prompt)

    return {
        "final_report": response.content
    }


# ==================================================
# 5. 创建 Graph
# ==================================================

builder = StateGraph(AgentState)


# ==================================================
# 6. 添加 Node
# ==================================================

builder.add_node(
    "diagnose",
    diagnose_node
)

builder.add_node(
    "report",
    report_node
)


# ==================================================
# 7. 添加 Edge
# ==================================================

builder.add_edge(
    START,
    "diagnose"
)

builder.add_edge(
    "diagnose",
    "report"
)

builder.add_edge(
    "report",
    END
)


# ==================================================
# 8. Compile
# ==================================================

graph = builder.compile()


# ==================================================
# 9. Invoke
# ==================================================

result = graph.invoke(
    {
        "user_question": "为什么这个商品表现不好？",

        "product_id": "SKU001",

        "ctr": 0.012,

        "cvr": 0.008,

        "diagnosis": "",

        "final_report": ""
    }
)


# ==================================================
# 10. 输出结果
# ==================================================

print("\n\n========== Diagnosis ==========")

print(
    result["diagnosis"]
)


print("\n\n========== Final Report ==========")

print(
    result["final_report"]
)



