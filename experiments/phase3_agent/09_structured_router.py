import os

from typing import TypedDict, Literal
from dotenv import load_dotenv
from pydantic import BaseModel, Field

from langgraph.graph import (
    StateGraph,
    START,
    END
)

from langchain_openai import ChatOpenAI


load_dotenv()


# ==================================================
# 1. 定义 Agent State
# ==================================================

class AgentState(TypedDict):

    user_question: str

    product_id: str
    ctr: float
    cvr: float

    diagnosis: str
    next_action: str

    image_score: float
    image_problem: str

    price_score: float
    price_problem: str

    final_report: str


# ==================================================
# 2. 定义 Structured Output Schema
# ==================================================

class DiagnosisResult(BaseModel):

    diagnosis: str = Field(
        description="根据当前已知数据得到的初步诊断"
    )

    next_action: Literal[
        "image",
        "price",
        "report"
    ] = Field(
        description="下一步应该执行的分析方向"
    )


# ==================================================
# 3. 初始化 LLM
# ==================================================

llm = ChatOpenAI(
    model="deepseek-v4-flash",
    api_key=os.getenv("DEEPSEEK_API_KEY"),
    base_url="https://api.deepseek.com",
    extra_body={
        "thinking": {
            "type": "disabled"
        }
    }
)


# DeepSeek 不支持 json_schema
# 使用 function_calling
diagnosis_llm = llm.with_structured_output(
    DiagnosisResult,
    method="function_calling"
)


# ==================================================
# 4. Diagnose Node
# ==================================================

def diagnose_node(state: AgentState):

    print("\n========== Diagnose Node ==========")

    prompt = f"""
你是一名电商数据分析专家。

用户问题：
{state["user_question"]}

商品ID：
{state["product_id"]}

CTR：
{state["ctr"]}

CVR：
{state["cvr"]}

请根据当前已有信息进行初步诊断。

下一步只能从以下三个动作中选择：

image
price
report

判断原则：

1. CTR明显偏低：
优先检查图片问题，选择 image。

2. CTR尚可但CVR明显偏低：
优先检查价格问题，选择 price。

3. 当前没有明显异常，或者已有信息足够：
选择 report。

禁止编造不存在的数据。
"""

    result = diagnosis_llm.invoke(
        prompt
    )

    print("diagnosis:")
    print(result.diagnosis)

    print("\nnext_action:")
    print(result.next_action)

    return {
        "diagnosis":
            result.diagnosis,

        "next_action":
            result.next_action
    }


# ==================================================
# 5. Image Tool Node
# ==================================================

def image_tool_node(state: AgentState):

    print("\n========== Image Tool Node ==========")

    image_score = 0.42

    image_problem = (
        "商品主体占比偏小，"
        "背景干扰较强，"
        "主视觉吸引力不足。"
    )

    return {
        "image_score":
            image_score,

        "image_problem":
            image_problem
    }


# ==================================================
# 6. Price Tool Node
# ==================================================

def price_tool_node(state: AgentState):

    print("\n========== Price Tool Node ==========")

    price_score = 0.58

    price_problem = (
        "商品价格高于同类商品平均水平，"
        "可能对转化率产生影响。"
    )

    return {
        "price_score":
            price_score,

        "price_problem":
            price_problem
    }


# ==================================================
# 7. Router
# ==================================================

def route_after_diagnosis(
    state: AgentState
) -> Literal[
    "image_tool",
    "price_tool",
    "report"
]:

    print("\n========== Router ==========")

    action = state["next_action"]

    print(
        "route:",
        action
    )

    if action == "image":
        return "image_tool"

    if action == "price":
        return "price_tool"

    return "report"


# ==================================================
# 8. Report Node
# ==================================================

def report_node(state: AgentState):

    print("\n========== Report Node ==========")

    prompt = f"""
你是一名电商运营分析专家。

用户问题：
{state["user_question"]}

商品ID：
{state["product_id"]}

CTR：
{state["ctr"]}

CVR：
{state["cvr"]}

初步诊断：
{state["diagnosis"]}

图片分析：
score = {state["image_score"]}
problem = {state["image_problem"]}

价格分析：
score = {state["price_score"]}
problem = {state["price_problem"]}

请生成最终业务分析报告。

要求：

1. 区分已知事实和推断。
2. 不允许编造数据。
3. 如果某个工具没有执行，
不要使用对应结果进行判断。
4. 给出最可能的问题。
5. 给出下一步建议。
"""

    response = llm.invoke(
        prompt
    )

    return {
        "final_report":
            response.content
    }


# ==================================================
# 9. 创建 Graph
# ==================================================

builder = StateGraph(
    AgentState
)


builder.add_node(
    "diagnose",
    diagnose_node
)

builder.add_node(
    "image_tool",
    image_tool_node
)

builder.add_node(
    "price_tool",
    price_tool_node
)

builder.add_node(
    "report",
    report_node
)


# ==================================================
# 10. Edge
# ==================================================

builder.add_edge(
    START,
    "diagnose"
)


builder.add_conditional_edges(
    "diagnose",
    route_after_diagnosis,
    {
        "image_tool":
            "image_tool",

        "price_tool":
            "price_tool",

        "report":
            "report"
    }
)


builder.add_edge(
    "image_tool",
    "report"
)

builder.add_edge(
    "price_tool",
    "report"
)

builder.add_edge(
    "report",
    END
)


# ==================================================
# 11. Compile
# ==================================================

graph = builder.compile()


# ==================================================
# 12. Invoke
# ==================================================

result = graph.invoke(
    {
        "user_question":
            "为什么这个商品表现不好？",

        "product_id":
            "SKU001",

        "ctr":
            0.055,

        "cvr":
            0.008,

        "diagnosis":
            "",

        "next_action":
            "",

        "image_score":
            0.0,

        "image_problem":
            "",

        "price_score":
            0.0,

        "price_problem":
            "",

        "final_report":
            ""
    }
)


# ==================================================
# 13. 输出
# ==================================================

print(
    "\n========== Final State =========="
)

for key, value in result.items():

    print(
        f"\n{key}:"
    )

    print(value)


print(
    "\n========== Final Report =========="
)

print(
    result["final_report"]
)



